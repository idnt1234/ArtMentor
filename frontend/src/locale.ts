export function resolveLocale(saved: string | null, preferred: readonly string[]): Locale {
  if (saved === "zh-CN" || saved === "en") return saved;
  for (const lang of preferred) {
    if (/^zh(?:-|$)/i.test(lang)) return "zh-CN";
    if (/^en(?:-|$)/i.test(lang)) return "en";
  }
  return "en";
}

let activeLocale: Locale | undefined;

export function currentLocale(): Locale {
  if (activeLocale) return activeLocale;
  let saved: string | null = null;
  try {
    saved = typeof localStorage === "undefined" ? null : localStorage.getItem(STORAGE_KEY);
  } catch {
    // Private browsing and embedded previews can deny storage.
  }
  return resolveLocale(saved, typeof navigator === "undefined" ? [] : navigator.languages);
}

export function rememberLocale(locale: Locale): void {
  activeLocale = locale;
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    // Keep the choice for the current session even when storage is blocked.
  }
}

export function translate(locale: Locale, key: string, values?: MessageValues): string {
  const message = locale === "zh-CN" && Object.hasOwn(chinese, key) ? chinese[key] : key;
  return values ? message.replace(/\{([a-zA-Z_]+)\}/g, (whole, name: string) => {
    return Object.hasOwn(values, name) ? String(values[name]) : whole;
  }) : message;
}

export function translateError(locale: Locale, message: string): string {
  const requestError = /^(Request|Export) failed \((\d+)\)$/.exec(message);
  if (requestError) {
    return translate(locale, requestError[1] === "Request" ? "Request failed ({status})" : "Export failed ({status})", {
      status: requestError[2],
    });
  }
  const quotaError = /^Daily AI limit reached \((\d+)\)\. It resets at 00:00 UTC\.$/.exec(message);
  if (quotaError) return translate(locale, "Daily AI limit reached ({limit}). It resets at 00:00 UTC.", { limit: quotaError[1] });
  const uploadError = /^Images must be (\d+) MB or smaller\.$/.exec(message);
  if (uploadError) return translate(locale, "Images must be {limit} MB or smaller.", { limit: uploadError[1] });
  return translate(locale, message);
}
